        $this->process($itip, $old, $expected);
    }

    public function testRequestUpdateSingleInstanceKeepsSeries(): void
    {
        $itip = <<<ICS
BEGIN:VCALENDAR
VERSION:2.0
METHOD:REQUEST
BEGIN:VEVENT
SEQUENCE:2
UID:foobar
DTSTART:20261112T163000Z
RECURRENCE-ID:20261112T163000Z
SUMMARY:Edited
END:VEVENT
END:VCALENDAR
ICS;

        $old = <<<ICS
BEGIN:VCALENDAR
BEGIN:VEVENT
SEQUENCE:1
UID:foobar
RRULE:FREQ=WEEKLY
DTSTART:20261029T163000Z
END:VEVENT
END:VCALENDAR
ICS;

        $expected = <<<ICS
BEGIN:VCALENDAR
BEGIN:VEVENT
SEQUENCE:1
UID:foobar
RRULE:FREQ=WEEKLY
DTSTART:20261029T163000Z
END:VEVENT
BEGIN:VEVENT
SEQUENCE:2
UID:foobar
DTSTART:20261112T163000Z
RECURRENCE-ID:20261112T163000Z
SUMMARY:Edited
END:VEVENT
END:VCALENDAR
ICS;

        $this->process($itip, $old, $expected);
    }

    public function testRequestUpdateSingleInstanceReplacesExistingInstance(): void
    {
        $itip = <<<ICS
BEGIN:VCALENDAR
VERSION:2.0
METHOD:REQUEST
BEGIN:VTIMEZONE
TZID:Europe/Berlin
BEGIN:STANDARD
DTSTART:16010101T030000
TZOFFSETFROM:+0200
TZOFFSETTO:+0100
RRULE:FREQ=YEARLY;BYDAY=-1SU;BYMONTH=10
END:STANDARD
END:VTIMEZONE
BEGIN:VEVENT
SEQUENCE:3
UID:foobar
DTSTART;TZID=Europe/Berlin:20261113T173000
RECURRENCE-ID;TZID=Europe/Berlin:20261112T173000
SUMMARY:Edited again
END:VEVENT
END:VCALENDAR
ICS;

        $old = <<<ICS
BEGIN:VCALENDAR
BEGIN:VEVENT
SEQUENCE:1
UID:foobar
RRULE:FREQ=WEEKLY
DTSTART:20261029T163000Z
END:VEVENT
BEGIN:VEVENT
SEQUENCE:2
UID:foobar
DTSTART:20261112T163000Z
RECURRENCE-ID:20261112T163000Z
SUMMARY:Edited
END:VEVENT
END:VCALENDAR
ICS;

        $expected = <<<ICS
BEGIN:VCALENDAR
BEGIN:VEVENT
SEQUENCE:1
UID:foobar
RRULE:FREQ=WEEKLY
DTSTART:20261029T163000Z
END:VEVENT
BEGIN:VTIMEZONE
TZID:Europe/Berlin
BEGIN:STANDARD
DTSTART:16010101T030000
TZOFFSETFROM:+0200
TZOFFSETTO:+0100
RRULE:FREQ=YEARLY;BYDAY=-1SU;BYMONTH=10
END:STANDARD
END:VTIMEZONE
BEGIN:VEVENT
SEQUENCE:3
UID:foobar
DTSTART;TZID=Europe/Berlin:20261113T173000
RECURRENCE-ID;TZID=Europe/Berlin:20261112T173000
SUMMARY:Edited again
END:VEVENT
END:VCALENDAR
ICS;

        $this->process($itip, $old, $expected);
    }

